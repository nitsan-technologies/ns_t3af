namespace NITSAN\NsT3AF\Mcp\Service;

use Psr\Http\Message\ServerRequestInterface;
use TYPO3\CMS\Backend\Utility\BackendUtility;
use TYPO3\CMS\Core\Core\Environment;
use TYPO3\CMS\Core\Core\SystemEnvironmentBuilder;
use TYPO3\CMS\Core\Database\ConnectionPool;
use TYPO3\CMS\Core\Exception\SiteNotFoundException;
use TYPO3\CMS\Core\Http\ServerRequest;
use TYPO3\CMS\Core\Site\SiteFinder;
use TYPO3\CMS\Core\Utility\GeneralUtility;

/**
 * Puts the TYPO3 site on {@see $GLOBALS['TYPO3_REQUEST']} for DataHandler page writes.
 *
 * cms-redirects (and slug handling) need the site attribute. Shared by
 * {@see DataHandlerService} and {@see RecordsApply\RecordsApplyService}.
 */
final class McpSiteRequestBootstrap
{
    public function __construct(
        private readonly SiteFinder $siteFinder,
        private readonly ?McpSlugRedirectGuard $slugRedirectGuard = null,
    ) {}

    /**
     * @return array{hadRequest: bool, original: mixed}
     */
    public function capture(): array
    {
        return [
            'hadRequest' => isset($GLOBALS['TYPO3_REQUEST']),
            'original' => $GLOBALS['TYPO3_REQUEST'] ?? null,
        ];
    }

    /**
     * @param array{hadRequest?: bool, original?: mixed} $snapshot
     */
    public function restore(array $snapshot): void
    {
        $hadRequest = (bool) ($snapshot['hadRequest'] ?? false);
        $originalRequest = $snapshot['original'] ?? null;

        if ($hadRequest && $originalRequest instanceof ServerRequestInterface) {
            $GLOBALS['TYPO3_REQUEST'] = $originalRequest;

            return;
        }

        if (!$hadRequest) {
            unset($GLOBALS['TYPO3_REQUEST']);
        }
    }

    /**
     * Attach the site for a live page uid. Returns false when the page has no site
     * (callers may warn and skip auto-redirects instead of failing the batch).
     */
    public function attachForPage(int $pageId): bool
    {
        $livePageId = $this->resolveLivePageUid($pageId);
        if ($livePageId <= 0) {
            return false;
        }

        try {
            $site = $this->siteFinder->getSiteByPageId($livePageId);
        } catch (SiteNotFoundException) {
            return false;
        }

        if (self::isBrokenAutogeneratedBase($site->getIdentifier(), (string) $site->getBase())) {
            return false;
        }

        $request = $GLOBALS['TYPO3_REQUEST'] ?? null;
        if ($request instanceof ServerRequestInterface) {
            $GLOBALS['TYPO3_REQUEST'] = $request->withAttribute('site', $site);

            return true;
        }

        $GLOBALS['TYPO3_REQUEST'] = (new ServerRequest((string) $site->getBase()))
            ->withAttribute('site', $site)
            ->withAttribute('applicationType', SystemEnvironmentBuilder::REQUESTTYPE_BE);

        return true;
    }

    /**
     * Resolve live page uids touched by a pages datamap/cmdmap and attach sites.
     *
     * @param array<mixed> $datamap
     * @param array<mixed> $cmdmap
     * @return list<string> warnings (e.g. pages with no site)
     */
    public function attachForPagesBatch(array $datamap, array $cmdmap): array
    {
        $pageIds = [];
        foreach (($datamap['pages'] ?? []) as $id => $fields) {
            if (!is_array($fields)) {
                continue;
            }
            if (str_starts_with((string) $id, 'NEW')) {
                $pid = (int) ($fields['pid'] ?? 0);
                if ($pid !== 0) {
                    $pageIds[] = abs($pid);
                }
                continue;
            }
            $pageIds[] = (int) $id;
        }

        foreach (array_keys($cmdmap['pages'] ?? []) as $uid) {
            $pageIds[] = (int) $uid;
        }

        $warnings = [];
        foreach (array_unique(array_filter($pageIds, static fn(int $uid): bool => $uid > 0)) as $pageId) {
            if (!$this->attachForPage($pageId)) {
                $this->slugRedirectGuard?->skipPage($pageId);
                $warnings[] = sprintf(
                    'Page %d has no site configuration; auto-redirects for slug changes were skipped.',
                    $pageId,
                );
            }
        }

        return $warnings;
    }

    /**
     * A new pid-0 page makes TYPO3 write config/sites/autogenerated-{uid}-*.
     * During MCP the request host is not a real site URL, so the generated slug
     * and redirect are unusable. Delete that site directory, put the caller's
     * slug back, and drop the broken redirect. A site that already has a real
     * http(s) host is left alone.
     *
     * @param array<mixed> $datamap
     * @param array<string, int> $created NEW id => uid
     * @return list<string>
     */
    public function discardBrokenAutogeneratedSites(array $datamap, array $created): array
    {
        $warnings = [];
        $pages = $datamap['pages'] ?? [];
        if (!is_array($pages)) {
            return $warnings;
        }

        foreach ($pages as $id => $fields) {
            if (!is_array($fields) || !str_starts_with((string) $id, 'NEW')) {
                continue;
            }
            if (!$this->placesNewPageAtSiteRoot($fields['pid'] ?? null)) {
                continue;
            }

            $uid = (int) ($created[(string) $id] ?? 0);
            if ($uid <= 0) {
                continue;
            }

            $identifier = self::autogeneratedSiteIdentifier($uid);
            $this->removeAutogeneratedSiteDirs($uid);
            $this->restoreCallerSlug($uid, (string) ($fields['slug'] ?? ''));
            $this->softDeleteBrokenRedirects($uid);
            $this->slugRedirectGuard?->skipPage($uid);
            $this->slugRedirectGuard?->forgetBrokenRedirects();

            $warnings[] = sprintf(
                'Page %d was created at the site root. The temporary site %s was removed so the slug stays the one you sent. Add a site configuration if this page should be its own site.',
                $uid,
                $identifier,
            );
        }

        return $warnings;
    }

    public static function isBrokenAutogeneratedBase(string $identifier, string $base): bool
    {
        if (!str_starts_with($identifier, 'autogenerated-')) {
            return false;
        }

        return !preg_match('#^https?://[a-z0-9.-]+(?:\:[0-9]+)?(?:/|$)#i', $base);
    }

    /**
     * A new page lands at pid 0 when the caller sent pid 0, or when append rewrote
     * that pid to "-{uid}" (insert after the last root page). DataHandler then
     * stores the row at that record's pid, which is still 0, and core creates a site.
     *
     * @param int|null $afterRecordPid pid of the record a negative pid points at
     */
    public static function newPageLandsAtSiteRoot(mixed $pid, ?int $afterRecordPid): bool
    {
        if (!is_int($pid) && !(is_string($pid) && preg_match('/^-?\d+$/', $pid) === 1)) {
            return false;
        }

        $pid = (int) $pid;
        if ($pid === 0) {
            return true;
        }

        return $pid < 0 && $afterRecordPid === 0;
    }

    public function placesNewPageAtSiteRoot(mixed $pid): bool
    {
        $afterRecordPid = null;
        if (is_int($pid) || (is_string($pid) && preg_match('/^-\d+$/', $pid) === 1)) {
            $numeric = (int) $pid;
            if ($numeric < 0) {
                $afterRecordPid = $this->pagePid(-$numeric);
            }
        }

        return self::newPageLandsAtSiteRoot($pid, $afterRecordPid);
    }

    /**
     * Same name TYPO3 uses in CreateSiteConfiguration: autogenerated-{uid}-{md5(uid)}.
     */
    public static function autogeneratedSiteIdentifier(int $uid): string
    {
        return 'autogenerated-' . $uid . '-' . md5((string) $uid);
    }

    /**
     * @return list<string> directory names removed
     */
    private function removeAutogeneratedSiteDirs(int $uid): array
    {
        $root = Environment::getConfigPath() . '/sites';
        $exact = $root . '/' . self::autogeneratedSiteIdentifier($uid);
        $matches = array_values(array_unique(array_merge(
            is_dir($exact) ? [$exact] : [],
            glob($root . '/autogenerated-' . $uid . '-*') ?: [],
        )));
        $removed = [];
        foreach ($matches as $dir) {
            if (!is_dir($dir)) {
                continue;
            }
            $name = basename($dir);
            if (!str_starts_with($name, 'autogenerated-' . $uid . '-')) {
                continue;
            }
            if (GeneralUtility::rmdir($dir, true)) {
                $removed[] = $name;
            }
        }

        return $removed;
    }

    /**
     * The auto site stores the root slug as "/" (language base) or as a path
     * that contains the broken base. Put the caller's slug back either way.
     */
    private function restoreCallerSlug(int $uid, string $requestedSlug): bool
    {
        try {
            $connection = GeneralUtility::makeInstance(ConnectionPool::class)->getConnectionForTable('pages');
            $stored = $connection->executeQuery('SELECT slug FROM pages WHERE uid = ?', [$uid])->fetchOne();
        } catch (\Throwable) {
            return false;
        }

        if (!is_string($stored)) {
            return false;
        }

        $slug = trim($requestedSlug);
        if ($slug === '' || str_contains($slug, 'autogenerated-') || str_contains($slug, '/http:')) {
            $slug = '/page-' . $uid;
        }
        if (!str_starts_with($slug, '/')) {
            $slug = '/' . $slug;
        }
        if ($stored === $slug) {
            return false;
        }

        try {
            $connection->update('pages', ['slug' => $slug], ['uid' => $uid]);
        } catch (\Throwable) {
            return false;
        }

        return true;
    }

    private function pagePid(int $uid): ?int
    {
        try {
            $pid = GeneralUtility::makeInstance(ConnectionPool::class)
                ->getConnectionForTable('pages')
                ->executeQuery('SELECT pid FROM pages WHERE uid = ?', [$uid])
                ->fetchOne();
        } catch (\Throwable) {
            return null;
        }

        return is_numeric($pid) ? (int) $pid : null;
    }

    private function softDeleteBrokenRedirects(int $uid): void
    {
        try {
            $connection = GeneralUtility::makeInstance(ConnectionPool::class)->getConnectionForTable('sys_redirect');
            $connection->executeStatement(
                'UPDATE sys_redirect SET deleted = 1 WHERE deleted = 0 AND target LIKE ? AND (source_path LIKE ? OR source_path LIKE ?)',
                ['%uid=' . $uid . '%', '%autogenerated-%', '%/http:%'],
            );
        } catch (\Throwable) {
        }
    }

    private function resolveLivePageUid(int $pageId): int
    {
        if ($pageId <= 0) {
            return $pageId;
        }

        $record = BackendUtility::getRecord('pages', $pageId, 'uid,t3ver_oid');
        if (!is_array($record)) {
            return $pageId;
        }

        $oid = (int) ($record['t3ver_oid'] ?? 0);

        return $oid > 0 ? $oid : (int) ($record['uid'] ?? $pageId);
    }
}
