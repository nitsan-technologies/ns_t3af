namespace NITSAN\NsT3AF\Tests\Unit\Mcp\Service;

use NITSAN\NsT3AF\Mcp\Service\McpSiteRequestBootstrap;
use NITSAN\NsT3AF\Mcp\Service\McpSlugRedirectGuard;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;
use TYPO3\CMS\Core\Database\ConnectionPool;

/**
 * @internal
 */
final class McpAutogeneratedSiteTest extends TestCase
{
    #[Test]
    public function brokenAutogeneratedBaseIsOnlyTheMalformedOne(): void
    {
        self::assertTrue(McpSiteRequestBootstrap::isBrokenAutogeneratedBase('autogenerated-12-abc', 'http:/autogenerated-12'));
        self::assertTrue(McpSiteRequestBootstrap::isBrokenAutogeneratedBase('autogenerated-12-abc', 'autogenerated-12'));
        self::assertFalse(McpSiteRequestBootstrap::isBrokenAutogeneratedBase('autogenerated-12-abc', 'https://example.com/autogenerated-12'));
        self::assertFalse(McpSiteRequestBootstrap::isBrokenAutogeneratedBase('camino', 'https://example.com/'));
        self::assertSame(
            'autogenerated-354-8dd48d6a2e2cad213179a3992c0be53c',
            McpSiteRequestBootstrap::autogeneratedSiteIdentifier(354),
        );
    }

    #[Test]
    public function appendAfterARootPageStillCountsAsASiteRoot(): void
    {
        self::assertTrue(McpSiteRequestBootstrap::newPageLandsAtSiteRoot(0, null));
        self::assertTrue(McpSiteRequestBootstrap::newPageLandsAtSiteRoot('0', null));
        self::assertTrue(McpSiteRequestBootstrap::newPageLandsAtSiteRoot('-45', 0));
        self::assertFalse(McpSiteRequestBootstrap::newPageLandsAtSiteRoot('-45', 2));
        self::assertFalse(McpSiteRequestBootstrap::newPageLandsAtSiteRoot(2, null));
        self::assertFalse(McpSiteRequestBootstrap::newPageLandsAtSiteRoot('NEWpage', null));
    }

    #[Test]
    public function brokenRedirectPathsAreDroppedFromTheReply(): void
    {
        $guard = new McpSlugRedirectGuard($this->createMock(ConnectionPool::class));
        $guard->rememberCreated([
            'uid' => 4,
            'source_host' => '*',
            'source_path' => '/http:/autogenerated-12/',
            'target' => 't3://page?uid=12',
        ]);
        $guard->rememberCreated([
            'uid' => 5,
            'source_host' => '*',
            'source_path' => '/old-slug',
            'target' => 't3://page?uid=12',
        ]);

        $kept = $guard->collectNewRedirects();

        self::assertCount(1, $kept);
        self::assertSame('/old-slug', $kept[0]['source_path']);
    }
}
